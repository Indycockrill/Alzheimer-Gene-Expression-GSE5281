# Gene Research Notes – GSE5281 Alzheimer’s Neuron Analysis

These notes summarize the background research I did on the top differentially expressed genes identified in this analysis.

## Upregulated Genes

### NEAT1
NEAT1 is a long non-coding RNA that helps form nuclear paraspeckles and regulates gene expression under stress. Multiple studies have found NEAT1 to be upregulated in Alzheimer’s disease brain tissue. It has been linked to astrocyte reactivity, memory deficits, and broader stress responses in the brain.

### ITPKB
ITPKB (Inositol-trisphosphate 3-kinase B) is involved in calcium signaling pathways. Research has shown that ITPKB expression and protein levels are elevated in Alzheimer’s brains. Functional studies suggest it can increase amyloid production, promote tau phosphorylation, and contribute to neuroinflammation.

### ACACB
ACACB (Acetyl-CoA Carboxylase Beta) regulates fatty-acid oxidation in mitochondria by producing malonyl-CoA, which inhibits the transport of fatty acids into mitochondria. Its upregulation in this analysis is consistent with altered energy and lipid metabolism, a known feature of Alzheimer’s neurons.

## Downregulated Genes

### ATP5B and ATP5C1
Both genes encode subunits of mitochondrial ATP synthase (Complex V), the enzyme that produces the majority of cellular ATP. Reduced expression of ATP synthase subunits is frequently reported in Alzheimer’s disease and supports the well-established finding of mitochondrial energy failure in affected neurons.

### TUBB
TUBB encodes beta-tubulin, a major building block of microtubules. Microtubules form the internal scaffolding of neurons and are essential for axonal transport. Downregulation of tubulin genes aligns with the cytoskeletal disruption and tau-related pathology that are central to Alzheimer’s disease.

### YWHAZ
YWHAZ encodes the 14-3-3 zeta protein, a signaling molecule that interacts with tau. 14-3-3 proteins are found in neurofibrillary tangles, and changes in YWHAZ expression have been associated with tau pathology and cognitive decline in Alzheimer’s disease.

## Overall Pattern
The combined changes point to neurons that are experiencing:
- Reduced energy production (ATP5B, ATP5C1)
- Weakened cytoskeletal structure (TUBB)
- Altered stress and calcium signaling (NEAT1, ITPKB)
- Shifts in lipid/energy metabolism (ACACB)
- Tau-related signaling disruption (YWHAZ)

These themes are consistent with major known mechanisms of Alzheimer’s disease.
